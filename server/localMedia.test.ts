async function fixture(t: any, assets = true) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ternfall-media-test-'));
  const storage = new StorageEngine(root); await storage.init();
  const service = new LocalMediaService(root, testBinaries);
  t.after(async () => { service.close(); storage.close(); await fs.rm(root, { recursive: true, force: true }); });
  const frames = path.join(root, 'projects', project, 'assets', 'flow_renders', episode);
  const audio = path.join(root, 'projects', project, 'audio', episode);
  await fs.mkdir(frames, { recursive: true }); await fs.mkdir(audio, { recursive: true });
  if (assets) {
    // Original synthetic test fixtures only; never automatically generated by production code.
    const buffer = await sharp({ create: { width: 1920, height: 1080, channels: 3, background: '#15737a' } }).png().toBuffer();
    await Promise.all(Array.from({ length: 24 }, (_, i) => fs.writeFile(path.join(frames, `frame_${String(i + 1).padStart(5, '0')}.png`), buffer)));
    await mediaProcess(testBinaries.ffmpeg, ['-nostdin', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=2', '-ar', '48000', '-ac', '2', path.join(audio, 'fixture_audio.wav')]);
  }
  return { root, service, storage, frames, audio };
}
async function api(t: any, service: LocalMediaService, storage: StorageEngine) {
  const app = express(); app.use(express.json());
  app.use('/api/projects/:id/local-renders', localMediaRouter(service, storage));
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  return `http://127.0.0.1:${address.port}/api/projects/${project}/local-renders`;
}

